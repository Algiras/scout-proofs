#!/usr/bin/env python3
"""ProVerif models of supervised delegation.

A supervisor holds the root credential. A child agent holds only a handle that
the supervisor signed for one exact operation tuple. The child is fully
attacker-controlled (its signing key is public), which models an agent steered
by injected content. Unbounded sessions.

Usage: python3 gen_delegation.py [--proverif proverif]
Exit 0 iff every query has the expected result.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

MODEL = r"""
free net: channel.
free prov: channel [private].      (* supervisor -> provider over TLS, carries the root credential *)
free appr: channel [private].      (* principal -> supervisor: approved operation tuples *)

type sskey. type spkey.
fun spk(sskey): spkey.
fun sign(bitstring, sskey): bitstring.
reduc forall m: bitstring, k: sskey; checksign(sign(m, k), spk(k)) = m.
reduc forall m: bitstring, k: sskey; getmsg(sign(m, k)) = m.

const handleTag, reqTag: bitstring.

event Approved(bitstring).          (* the principal approved this exact operation tuple *)
event Executed(bitstring).          (* the provider executed it under the root credential *)
event ChildServed(bitstring).

(* D1 *) query x: bitstring; event(Executed(x)) ==> event(Approved(x)).
(* D2 *) query secret rootToken.
(* R  *) query x: bitstring; event(ChildServed(x)).

let Principal() =
  ! new op: bitstring; event Approved(op); out(net, op); out(appr, op).

let Provider(rootTok: bitstring) =
  ( ! in(prov, (=rootTok, op: bitstring)); event Executed(op); out(net, op) )
  | ( ! in(net, (=rootTok, op: bitstring)); event Executed(op); out(net, op) ).   (* the public API: anyone holding the credential *)

let Supervisor(skSup: sskey, rootToken: bitstring) =
  ( (* issue a handle for an approved tuple, bound to the child's key *)
    ! in(appr, op: bitstring); in(net, cvk: spkey);
      out(net, sign((handleTag, cvk, op), skSup)) )
  | ( (* mediate one operation: handle, child proof, exact tuple, then inject the credential *)
    ! in(net, (h: bitstring, rq: bitstring));
      let (=handleTag, cvk: spkey, hop: bitstring) = checksign(h, spk(skSup)) in
      let (=reqTag, rop: bitstring) = checksign(rq, cvk) in
      @TUPLECHECK@
      event ChildServed(rop);
      out(prov, (rootToken, rop)) )
  @TOKENTOCHILD@.

process
  new skSup: sskey; new rootToken: bitstring; new skChild: sskey;
  out(net, spk(skSup)); out(net, skChild);            (* the child agent is the attacker *)
  ( Principal() | Provider(rootToken) | Supervisor(skSup, rootToken) )
"""

SCENARIOS = {
    "d_supervised_delegation": ("supervisor checks the exact tuple; the child is attacker-controlled",
                                {"TUPLECHECK": "if rop = hop then", "TOKENTOCHILD": ""}, True, True),
    "d_x_no_tuple_check": ("broken: supervisor injects the credential for whatever the child proposes",
                           {"TUPLECHECK": "", "TOKENTOCHILD": ""}, False, True),
    "d_x_child_holds_token": ("baseline: the child is handed the root credential",
                              {"TUPLECHECK": "if rop = hop then", "TOKENTOCHILD": "| out(net, rootToken)"},
                              False, False),
}
QNAMES = ["D1 the provider executes under the root credential only tuples the principal approved",
          "D2 the root credential stays secret from the child"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--proverif", default="proverif")
    a = ap.parse_args()
    ok = True
    for name, (desc, subs, e1, e2) in SCENARIOS.items():
        src = MODEL
        for k, v in subs.items():
            src = src.replace(f"@{k}@", v)
        with open(os.path.join(HERE, name + ".pv"), "w") as f:
            f.write(f"(* {desc} *)\n(* generated by gen_delegation.py; do not edit *)\n" + src)
        out = subprocess.run([a.proverif, name + ".pv"], capture_output=True, text=True, timeout=300, cwd=HERE)
        text = out.stdout + out.stderr
        with open(os.path.join(HERE, name + ".log"), "w") as f:
            f.write(text)
        res = re.findall(r"^RESULT (.*?) (is true|is false|cannot be proved)\.", text, flags=re.M)
        print(f"\n{name}: {desc}")
        if len(res) != 3:
            ok = False
            print("  ERROR: expected 3 results, got", len(res), "\n", text[-800:])
            continue
        for i, exp in enumerate((e1, e2)):
            got = res[i][1]
            good = got == ("is true" if exp else "is false")
            ok &= good
            verdict = "PROVED" if got == "is true" else ("ATTACK" if got == "is false" else "NOT PROVED")
            print(f"  {verdict:10} {QNAMES[i]}{'' if good else '   <-- UNEXPECTED'}")
        reach = res[2][1] == "is false"
        ok &= reach
        print(f"  {'REACHABLE' if reach else 'UNREACHABLE':10} sanity: a child operation is served")
    print("\nRESULT:", "all scenarios as expected" if ok else "MISMATCH")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
